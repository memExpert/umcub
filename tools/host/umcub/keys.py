"""Keys of the umcub link SECURE mode as C arrays (what CMake embeds).

- device key (EC P-256, private): the bootloader's static key for the session
  key agreement (ECDH); its public half goes to the host;
- admin key (EC P-256): hosts sign the challenge with the private half; only
  the public half is embedded in the bootloader (a PEM with either half works).

The device key for encrypted images comes from `imgtool getpriv`, see
umcub_generate_enc_key() in cmake/umcub_imgtool.cmake.
"""
from pathlib import Path

from .errors import UmcubError


def load(path):
    """An EC P-256 key (private or public PEM)."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    try:
        data = Path(path).read_bytes()
    except OSError as e:
        raise UmcubError(f"{path}: {e.strerror}") from e
    try:
        key = serialization.load_pem_private_key(data, password=None)
    except (ValueError, TypeError):
        key = serialization.load_pem_public_key(data)
    if not isinstance(key, (ec.EllipticCurvePrivateKey, ec.EllipticCurvePublicKey)) or \
            key.curve.name != "secp256r1":
        raise UmcubError(f"{path}: not an EC P-256 key")
    return key


def _private(key, path, what):
    from cryptography.hazmat.primitives.asymmetric import ec
    if not isinstance(key, ec.EllipticCurvePrivateKey):
        raise UmcubError(f"{path}: {what} must be a private key")
    return key.private_numbers().private_value.to_bytes(32, "big")


def raw_pub(key):
    """Public key as X || Y (64 bytes)."""
    from cryptography.hazmat.primitives.asymmetric import ec
    pub = key.public_key() if isinstance(key, ec.EllipticCurvePrivateKey) else key
    n = pub.public_numbers()
    return n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


def write_if_changed(path, text):
    out = Path(path)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


def device_c(device, admin):
    """Bootloader side: device private key, admin public key."""
    return ("/* Generated by umcub keys c - umcub link SECURE keys. */\n#include <stdint.h>\n\n"
            "/* Device static key (private scalar, big endian): session ECDH. */\n" +
            c_array("umcub_link_device_priv", _private(load(device), device, "the device key")) +
            "\n/* Admin public key (X || Y): verifies the host's AUTH signature. */\n" +
            c_array("umcub_link_admin_pub", raw_pub(load(admin))))


def host_c(device, admin):
    """Host side for C host tools and tests: admin private key, device public key."""
    return ("/* Generated by umcub keys host-c - umcub link host side. */\n#include <stdint.h>\n\n"
            "/* Admin private scalar (big endian): signs the challenge. */\n" +
            c_array("umcub_link_host_admin_priv", _private(load(admin), admin, "the host side needs the admin key")) +
            "\n/* Device public key (X || Y): session ECDH. */\n" +
            c_array("umcub_link_host_device_pub", raw_pub(load(device))))
