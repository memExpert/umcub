"""Linker script fragments of the application slots (GNU ld): the MEMORY block of
an image and slot, with the region names of STM32CubeMX's scripts, so that a
Cube (or any) linker script uses it with one line in place of its own MEMORY
block:  INCLUDE umcub_app_img0_slot0.ld  (and -L <directory of the fragment>).

FLASH is the slot's window (behind the image header, before the trailer
reserve), the RAM region that holds the bootloader handoff area ends below it.
"""
from pathlib import Path

KB = 1024


def name(image, slot):
    return f"umcub_app_img{image}_slot{slot}.ld"


def core_of(cfg, image, core):
    """The core an image runs on: dual-core single boot has the CM4 application as image 1."""
    return ("cm7", "cm4")[image] if cfg["DUALCORE_MODE"] == 1 else core


def _ram(cfg, core):
    """[(region, origin, length, comment)] of the RAM the application may use."""
    if cfg.family == "stm32h7":
        if core == "cm4":
            return [("RAM", 0x10000000, 288 * KB, "D2 SRAM1-3 (CM4 alias)")]
        # 0x3800FE00..: the handoff areas of both cores (dual-core parts), kept over reset
        return [("DTCMRAM", 0x20000000, 128 * KB, ""),
                ("RAM_D1", 0x24000000, 512 * KB, "AXI SRAM"),
                ("RAM_D2", 0x30000000, 288 * KB, ""),
                ("RAM_D3", 0x38000000, 0x3800FE00 - 0x38000000, "end: bootloader handoff"),
                ("ITCMRAM", 0x00000000, 64 * KB, "")]
    shared = cfg["SHARED_RAM_ADDR"]
    return [("RAM", 0x20000000, shared - 0x20000000, f"end (0x{shared:08X}): bootloader handoff")]


def memory(cfg, image, slot, core=""):
    """The fragment of an image and slot (text)."""
    addr, size = cfg.slot(image, slot)
    origin, length = cfg.window(image, slot)
    core = core_of(cfg, image, core)
    regions = [("FLASH", "rx", origin, length,
                f"slot 0x{addr:08X} + 0x{size:X}: header 0x{cfg['IMAGE_HEADER_SIZE']:X} before, trailer after")]
    regions += [(r, "xrw", o, ln, c) for r, o, ln, c in _ram(cfg, core)]
    w = max(len(r[0]) for r in regions)
    lines = [f"/* Generated by umcub ({cfg.board_name}{', ' + core if core else ''}, {cfg.mcu}): "
             f"image {image}, slot {slot}. Do not edit:",
             " * it changes with the bootloader configuration. Use it in place of the MEMORY block of",
             f" * the application's linker script:  INCLUDE {name(image, slot)}  */",
             "MEMORY", "{"]
    for n, attr, o, ln, c in regions:
        lines.append(f"  {n:<{w}} ({attr}){' ' * (4 - len(attr))}: ORIGIN = 0x{o:08X}, LENGTH = 0x{ln:X}"
                     + (f"   /* {c} */" if c else ""))
    return "\n".join(lines + ["}", ""])


def fragments(cfg, core=""):
    """{file name: text} of every image and slot an application can be linked for
    (slot 1 only in the direct-xip modes)."""
    return {name(i, s): memory(cfg, i, s, core)
            for i in cfg.images() for s in ((0, 1) if cfg.xip() else (0,))}


def write(cfg, out_dir, core=""):
    """The fragments into out_dir (unchanged files are not touched); returns their paths."""
    out = []
    Path(out_dir).mkdir(parents=True, exist_ok=True)
    for n, text in fragments(cfg, core).items():
        p = Path(out_dir) / n
        if not p.is_file() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
        out.append(p)
    return out
