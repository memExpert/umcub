#!/usr/bin/env python3
"""Generate the part and pin menus of the Kconfig tree from ST's pin data
(third_party/st/stm32_open_pin_data, the STM32CubeMX database):

  tools/build/gen_kconfig.py [--check]

port/kconfig_gen/*.kconfig (sourced by port/Kconfig and config/Kconfig):
  parts.kconfig       the part choice: every part number of the lines the ports
                      support, with package, flash and RAM; per part what it has
                      (USART instances, USB, CAN, Ethernet) and its pin set
  pins.kconfig        hidden PIN_<Pxn>: the selected part brings that pin out
  <option>.kconfig    a choice per pin option with only the pins that fit the
                      selected part, instance and signal (UART TX/RX/DE, CAN
                      TX/RX, the RMII pins, entry button, status LED); a hidden
                      string <OPTION>_PIN carries "PA9:7" (with the alternate
                      function) or "PA9" (plain GPIO, STM32F1)

Run it after adding a part line to LINES (and the port) or updating the pin
data; --check fails when the files are not up to date (build matrix).
"""
import argparse
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import check_pins as cp  # noqa: E402

DATA = ROOT / "third_party/st/stm32_open_pin_data"
OUT = ROOT / "port/kconfig_gen"

# Lines the ports support: CMSIS define, part-name pattern, family.
LINES = [
    ("STM32F103xB", r"STM32F103.[8B]..", "STM32F1"),
    ("STM32F411xE", r"STM32F411.[CE]..", "STM32F4"),
    ("STM32H742xx", r"STM32H742.[GI]..", "STM32H7"),
    ("STM32H743xx", r"STM32H743.[GI]..", "STM32H7"),
    ("STM32H753xx", r"STM32H753.I..", "STM32H7"),
    ("STM32H745xx", r"STM32H745.I..", "STM32H7"),
    ("STM32H745xG", r"STM32H745.G..", "STM32H7"),
    ("STM32H747xx", r"STM32H747.I..", "STM32H7"),
    ("STM32H747xG", r"STM32H747.G..", "STM32H7"),
    ("STM32H755xx", r"STM32H755.I..", "STM32H7"),
    ("STM32H757xx", r"STM32H757.I..", "STM32H7"),
]
DUALCORE = {"STM32H745xx", "STM32H745xG", "STM32H747xx", "STM32H747xG", "STM32H755xx", "STM32H757xx"}

# What the family ports drive (port/stm32<fam>/uart.c, can.c, eth.c, usb.c).
PORT_UARTS = {"STM32F1": [1, 2, 3], "STM32F4": [1, 2, 6], "STM32H7": [1, 2, 3, 4, 5, 6, 7, 8]}
PORT_CAN = {"STM32F1", "STM32H7"}           # CAN1 / FDCAN1
PORT_ETH = {"STM32H7"}
PORT_USB = {"STM32F1", "STM32F4", "STM32H7"}
# STM32F1 has no AF numbers: the AFIO remap is chosen by the pin pair
# (port/stm32f1/uart.c, can.c), so RX follows TX.
F1_UART_PAIRS = {1: [("PA9", "PA10"), ("PB6", "PB7")], 2: [("PA2", "PA3"), ("PD5", "PD6")],
                 3: [("PB10", "PB11"), ("PC10", "PC11"), ("PD8", "PD9")]}
F1_CAN_PAIRS = [("PA12", "PA11"), ("PB9", "PB8"), ("PD1", "PD0")]
RMII = ["REF_CLK", "MDIO", "CRS_DV", "MDC", "RXD0", "RXD1", "TX_EN", "TXD0", "TXD1"]

HEADER = "# Generated by tools/build/gen_kconfig.py from ST's pin data - do not edit.\n"
PIN_HELP = ["The pins that carry this signal on this package; the alternate function",
            "is filled in."]
F1_PAIR_HELP = ["STM32F1: TX and RX go in pairs (AFIO remap)."]


def sym(text):
    return re.sub(r"[^A-Z0-9_]", "_", text.upper())


def expand(ref):
    """STM32F411C(C-E)Ux -> [STM32F411CCUx, STM32F411CEUx] (alternatives, in the
    order of the <Flash> / <Ram> entries)."""
    m = re.search(r"\(([A-Z0-9-]+)\)", ref)
    if not m:
        return [ref]
    return [ref[:m.start()] + c + ref[m.end():] for c in m.group(1).split("-")]


def pin_key(p):
    return (p[1], int(p[2:]))


class Part:
    def __init__(self, name, line, family, f, package, flash, ram, pins, ips):
        self.name, self.line, self.family, self.file = name, line, family, f
        self.package, self.flash, self.ram, self.pins, self.ips = package, flash, ram, pins, ips
        self.sym = "PART_" + sym(name)


def load_parts():
    parts = []
    for f in sorted(os.listdir(DATA / "mcu")):
        if not f.endswith(".xml"):
            continue
        root = cp.ET.parse(DATA / "mcu" / f).getroot()
        names = expand(root.get("RefName") or f[:-4])
        flash = [int(e.text) for e in cp.children(root, "Flash")]
        ram = [int(e.text) for e in cp.children(root, "Ram")]
        for i, name in enumerate(names):
            for define, pat, fam in LINES:
                if re.fullmatch(pat, name):
                    _, pins = cp.package_pins(str(DATA), f)
                    ips = {ip.get("InstanceName") for ip in cp.children(root, "IP")}
                    ips |= {ip.get("Name") for ip in cp.children(root, "IP")}
                    parts.append(Part(name, define, fam, f, root.get("Package"),
                                      flash[min(i, len(flash) - 1)], ram[min(i, len(ram) - 1)], pins, ips))
    return parts


def signals_of(parts):
    """line -> signal -> {pin: AF or None}: AF numbers from the GPIO data where
    the family has them, else (STM32F1) the signals the pins carry."""
    out = {}
    for line in {p.line for p in parts}:
        files = sorted({p.file for p in parts if p.line == line})
        sig, _ = cp.gpio_modes(str(DATA), line, files)
        table = {}
        if sig is not None:
            for s, pins in sig.items():
                for pin, af in pins:
                    table.setdefault(s, {})[pin] = af
        else:
            for f in files:
                root = cp.ET.parse(DATA / "mcu" / f).getroot()
                for pin in cp.children(root, "Pin"):
                    name = re.match(r"P[A-K]\d+", pin.get("Name") or "")
                    if name:
                        for s in cp.children(pin, "Signal"):
                            table.setdefault(s.get("Name"), {})[name.group(0)] = None
        out[line] = table
    return out


def or_expr(items):
    items = sorted(set(items))
    return " || ".join(items) if items else "n"


def wrap_default(value, cond):
    return f"\tdefault {value} if {cond}\n"


class Gen:
    def __init__(self):
        self.parts = load_parts()
        self.lines = {p.line for p in self.parts}
        self.sig = signals_of(self.parts)
        self.files = {}
        # pin sets: parts with the same pins share one hidden symbol
        self.pinsets = {}
        for p in self.parts:
            self.pinsets.setdefault(frozenset(p.pins), []).append(p)
        self.pinset_sym = {ps: f"PINSET_{i}" for i, ps in enumerate(sorted(self.pinsets, key=lambda s: sorted(s)))}
        self.all_pins = sorted({pin for p in self.parts for pin in p.pins}, key=pin_key)

    def line_sym(self, line):
        return "MCU_" + sym(line)

    def parts_kconfig(self):
        t = HEADER + "\n"
        t += "choice PART_CHOICE\n\tprompt \"MCU part\"\n\thelp\n"
        t += "\t  The part number on the chip (the last characters, temperature range and\n"
        t += "\t  packing, do not matter: x). Only lines the ports are verified for are\n"
        t += "\t  listed: docs/porting.md, \"Adding a part\".\n\n"
        for p in sorted(self.parts, key=lambda p: p.name):
            t += f"config {p.sym}\n\tbool \"{p.name}  {p.package}, {p.flash} KiB flash, {p.ram} KiB RAM\"\n"
            t += f"\tselect {self.line_sym(p.line)}\n"
        t += "endchoice\n\n"
        for line in sorted(self.lines):
            fam = next(p.family for p in self.parts if p.line == line)
            t += f"config {self.line_sym(line)}\n\tbool\n\tselect FAMILY_{fam}\n"
            if line in DUALCORE:
                t += "\tselect MCU_DUALCORE\n"
        t += "\nconfig MCU\n\tstring\n"
        for line in sorted(self.lines):
            t += wrap_default(f'"{line}"', self.line_sym(line))
        t += "\thelp\n\t  CMSIS device define of the part (family port, startup, CPU flags).\n"
        t += "\nconfig MCU_PART\n\tstring\n"
        for p in sorted(self.parts, key=lambda p: p.name):
            t += wrap_default(f'"{p.name}"', p.sym)
        t += "\thelp\n\t  The part number (ST pin data name): the pins of its package.\n"
        for what, key in (("FLASH_KB", "flash"), ("RAM_KB", "ram")):
            t += f"\nconfig {what}\n\tint\n"
            by = {}
            for p in self.parts:
                by.setdefault(getattr(p, key), []).append(p.sym)
            for v, syms in sorted(by.items()):
                t += wrap_default(v, or_expr(syms))
        # pin sets and peripherals
        for ps, syms in sorted(self.pinset_sym.items(), key=lambda kv: kv[1]):
            t += f"\nconfig {syms}\n\tbool\n" + wrap_default("y", or_expr(p.sym for p in self.pinsets[ps]))
        for inst in range(1, 11):
            has = [p.sym for p in self.parts
                   if inst in PORT_UARTS[p.family] and ({f"USART{inst}", f"UART{inst}"} & p.ips)]
            if has:
                t += f"\nconfig HAS_UART{inst}\n\tbool\n" + wrap_default("y", or_expr(has))
        for name, fams, ips in (("HAS_USB", PORT_USB, {"USB", "USB_OTG_FS"}),
                                ("HAS_CAN", PORT_CAN, {"CAN", "CAN1", "FDCAN", "FDCAN1"}),
                                ("HAS_ETH", PORT_ETH, {"ETH"})):
            has = [p.sym for p in self.parts if p.family in fams and ips & p.ips]
            t += f"\nconfig {name}\n\tbool\n" + wrap_default("y", or_expr(has))
        return t

    def pins_kconfig(self):
        t = HEADER
        for pin in self.all_pins:
            sets = [s for ps, s in self.pinset_sym.items() if pin in ps]
            t += f"\nconfig PIN_{pin}\n\tbool\n" + wrap_default("y", or_expr(sets))
        return t

    def choice(self, name, prompt, members, string_sym, extra="", none=None, help_=None):
        """members: [(member sym, prompt, depends, value, value condition list [(value, cond)])]"""
        t = HEADER + f"\nchoice {name}_CHOICE\n\tprompt \"{prompt}\"\n{extra}"
        if help_:
            t += "\thelp\n" + "".join(f"\t  {h}\n" for h in help_)
        if none:
            t += f"\nconfig {none[0]}\n\tbool \"{none[1]}\"\n"
        defaults = []
        for msym, mprompt, dep, values in members:
            t += f"\nconfig {msym}\n\tbool \"{mprompt}\"\n\tdepends on {dep}\n"
            defaults += [(v, f"{msym} && {c}" if c else msym) for v, c in values]
        t += "\nendchoice\n"
        t += f"\nconfig {string_sym}\n\tstring\n"
        for v, c in defaults:
            t += wrap_default(f'"{v}"', c)
        t += '\tdefault ""\n'
        return t

    def signal_members(self, prefix, opt, signal_fn, instances, pairs=None):
        """Choice members for a pin carrying a signal: per pin the lines and
        instances where it carries it (and the AF there)."""
        by_pin = {}
        for line in self.lines:
            for inst in instances:
                for s in signal_fn(inst):
                    for pin, af in self.sig[line].get(s, {}).items():
                        by_pin.setdefault(pin, []).append((line, inst, af, s))
        members = []
        for pin in sorted(by_pin, key=pin_key):
            groups, sigs = {}, set()        # (instance, AF, pair) -> lines
            for line, inst, af, s in by_pin[pin]:
                pc = pairs(line, inst, pin) if pairs is not None else None
                if pc is False:
                    continue
                groups.setdefault((inst, af, pc or ""), []).append(self.line_sym(line))
                sigs.add(s)
            conds, values = [], []
            for (inst, af, pc), lines in sorted(groups.items(), key=lambda kv: str(kv[0])):
                c = [f"({or_expr(lines)})" if len(lines) > 1 else lines[0]]
                if len(instances) > 1:
                    c.append(f"{opt}_INSTANCE_{inst}")
                if pc:
                    c.append(pc)
                c = " && ".join(c)
                conds.append(f"({c})")
                values.append((f"{pin}:{af}" if af is not None else pin, f"({c})"))
            if conds:
                members.append((f"{prefix}_{pin}", f"{pin} ({'/'.join(sorted(sigs))})",
                                f"PIN_{pin} && ({' || '.join(conds)})", values))
        return members

    def gpio_members(self, prefix):
        return [(f"{prefix}_{pin}", pin, f"PIN_{pin}", [(pin, None)]) for pin in self.all_pins]

    def generate(self):
        f = {"parts.kconfig": self.parts_kconfig(), "pins.kconfig": self.pins_kconfig()}
        # UART instance
        t = HEADER + "\nchoice UART_INSTANCE_CHOICE\n\tprompt \"USART\"\n\thelp\n" \
            "\t  The USART of the transport and of the boot log, those this part has.\n"
        insts = sorted({i for fam in PORT_UARTS.values() for i in fam})
        for i in insts:
            t += f"\nconfig UART_INSTANCE_{i}\n\tbool \"USART{i} / UART{i}\"\n\tdepends on HAS_UART{i}\n"
        t += "\nendchoice\n\nconfig UART_INSTANCE\n\tint\n"
        for i in insts:
            t += wrap_default(i, f"UART_INSTANCE_{i}")
        f["uart_instance.kconfig"] = t

        def f1_uart_pair(line, inst, pin, rx):
            if not line.startswith("STM32F1"):
                return None
            for tx_, rx_ in F1_UART_PAIRS.get(inst, []):
                if (rx_ if rx else tx_) == pin:
                    return f"UART_TX_{tx_}" if rx else ""
            return False
        f["uart_tx.kconfig"] = self.choice(
            "UART_TX", "TX pin",
            self.signal_members("UART_TX", "UART", lambda i: [f"USART{i}_TX", f"UART{i}_TX"], insts,
                                lambda line, i, pin: f1_uart_pair(line, i, pin, False)),
            "UART_TX_PIN", help_=PIN_HELP + F1_PAIR_HELP)
        f["uart_rx.kconfig"] = self.choice(
            "UART_RX", "RX pin",
            self.signal_members("UART_RX", "UART", lambda i: [f"USART{i}_RX", f"UART{i}_RX"], insts,
                                lambda line, i, pin: f1_uart_pair(line, i, pin, True)),
            "UART_RX_PIN", help_=PIN_HELP + F1_PAIR_HELP)
        # DE: none, any GPIO (software), or the USART's DE pin (H7: hardware timing)
        hw = [(m[0] + "_HW", m[1].replace(")", ", hardware DE)"), m[2],
               [(v, c) for v, c in m[3] if ":" in v])
              for m in self.signal_members("UART_DE", "UART", lambda i: [f"USART{i}_DE", f"UART{i}_DE"], insts)
              if any(":" in v for v, _ in m[3]) and "H7" in m[2]]
        f["uart_de.kconfig"] = self.choice(
            "UART_DE", "RS485 driver-enable pin", hw + self.gpio_members("UART_DE"), "UART_DE_PIN",
            extra="\tdefault UART_DE_NONE\n",
            none=("UART_DE_NONE", "none (plain UART)"),
            help_=["DE (with /RE) of the transceiver, switched by software; on the STM32H7",
                   "the USART's own DE pin times it in hardware."])

        def f1_can_pair(line, inst, pin, rx):
            if not line.startswith("STM32F1"):
                return None
            for tx_, rx_ in F1_CAN_PAIRS:
                if (rx_ if rx else tx_) == pin:
                    return f"CAN_TX_{tx_}" if rx else ""
            return False
        for d, rx in (("TX", False), ("RX", True)):
            f[f"can_{d.lower()}.kconfig"] = self.choice(
                f"CAN_{d}", f"{d} pin",
                self.signal_members(f"CAN_{d}", "CAN", lambda i, d=d: [f"FDCAN{i}_{d}", f"CAN{i}_{d}", f"CAN_{d}"],
                                    [1], lambda line, i, pin, rx=rx: f1_can_pair(line, i, pin, rx)),
                f"CAN_{d}_PIN", help_=PIN_HELP + F1_PAIR_HELP)
        t = ""
        for s in RMII:
            t += self.choice(f"ETH_RMII_{s}", f"RMII {s}",
                             self.signal_members(f"ETH_RMII_{s}", "ETH", lambda i, s=s: [f"ETH_{s}"], [1]),
                             f"ETH_RMII_{s}_PIN", help_=PIN_HELP)
        f["eth_rmii.kconfig"] = t
        f["entry_gpio.kconfig"] = self.choice("ENTRY_GPIO", "Entry pin", self.gpio_members("ENTRY_GPIO"),
                                              "ENTRY_GPIO_PIN", help_=["The pin read at reset, any pin of this package."])
        f["status_led.kconfig"] = self.choice("STATUS_LED", "LED pin", self.gpio_members("STATUS_LED"),
                                              "STATUS_LED_PIN", help_=["The pin of the LED, any pin of this package."])
        return f


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the generated files are not up to date")
    a = ap.parse_args()
    files = Gen().generate()
    stale = []
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        p = OUT / name
        if not p.is_file() or p.read_text() != text:
            stale.append(name)
            if not a.check:
                p.write_text(text)
    if a.check and stale:
        sys.exit(f"port/kconfig_gen: {', '.join(stale)} not up to date - run tools/build/gen_kconfig.py")
    print(f"port/kconfig_gen: {len(files)} files, {len(stale)} {'stale' if a.check else 'written'}")


if __name__ == "__main__":
    main()
